import { randomUUID } from "node:crypto";

import { getCloudinaryClient } from "../config/cloudinary.js";
import { AppError } from "../utils/appError.js";

// ============================================
// CONFIGURATION
// ============================================

const ACCOUNT_TYPES = ["customers", "staff"];

const ASSET_CATEGORIES = ["profile", "documents"];

const ALLOWED_RESOURCE_TYPES = ["image", "raw"];

const DEFAULT_DOWNLOAD_EXPIRY_SECONDS = 15 * 60;

// ============================================
// SHARED VALIDATION HELPERS
// ============================================

const getResourceType = (mimeType) => {
  if (typeof mimeType !== "string") {
    throw new AppError("A valid file MIME type is required.", 400);
  }

  if (mimeType.startsWith("image/")) {
    return "image";
  }

  if (
    mimeType === "application/pdf" ||
    mimeType === "application/octet-stream"
  ) {
    return "raw";
  }

  throw new AppError("Unsupported file type.", 400);
};

const sanitizeFilename = (filename) => {
  if (typeof filename !== "string" || !filename.trim()) {
    return null;
  }

  return filename
    .trim()
    .replace(/[^\w.-]/g, "_")
    .slice(0, 150);
};

const validateAccountReference = ({
  accountType,
  accountId,
  assetCategory,
}) => {
  if (!ACCOUNT_TYPES.includes(accountType)) {
    throw new AppError("Invalid account type for file storage.", 400);
  }

  if (typeof accountId !== "string" || !/^[a-f\d]{24}$/i.test(accountId)) {
    throw new AppError("A valid account ID is required.", 400);
  }

  if (!ASSET_CATEGORIES.includes(assetCategory)) {
    throw new AppError("Invalid account asset category.", 400);
  }
};

// ============================================
// 1. UPLOAD ACCOUNT ASSET
// ============================================

/**
 * Uploads an authenticated Customer or Staff asset.
 *
 * Files are stored in account-specific folders.
 * Public IDs are generated by the backend.
 */
export const uploadAccountAsset = async ({
  buffer,
  mimeType,
  originalFilename,
  accountType,
  accountId,
  assetCategory,
}) => {
  if (!Buffer.isBuffer(buffer) || buffer.length === 0) {
    throw new AppError("A valid file is required for upload.", 400);
  }

  validateAccountReference({
    accountType,
    accountId,
    assetCategory,
  });

  const resourceType = getResourceType(mimeType);

  if (!ALLOWED_RESOURCE_TYPES.includes(resourceType)) {
    throw new AppError("Unsupported Cloudinary resource type.", 400);
  }

  const cloudinary = getCloudinaryClient();

  const publicId = [
    "lafams",
    accountType,
    accountId,
    assetCategory,
    randomUUID(),
  ].join("/");

  try {
    const result = await new Promise((resolve, reject) => {
      const uploadStream = cloudinary.uploader.upload_stream(
        {
          public_id: publicId,
          resource_type: resourceType,
          type: "authenticated",
          overwrite: false,
          unique_filename: false,
          use_filename: false,
          tags: ["lafams", accountType, assetCategory],
        },
        (error, uploadResult) => {
          if (error) {
            return reject(error);
          }

          return resolve(uploadResult);
        },
      );

      uploadStream.end(buffer);
    });

    return {
      publicId: result.public_id,
      assetId: result.asset_id || null,
      resourceType: result.resource_type,
      deliveryType: "authenticated",
      format: result.format || null,
      bytes: result.bytes || 0,
      originalFilename: sanitizeFilename(originalFilename),
      version: result.version || null,
    };
  } catch {
    throw new AppError("Account file upload failed. Please try again.", 502);
  }
};

// ============================================
// 2. DELETE ACCOUNT ASSET
// ============================================

/**
 * Deletes an authenticated asset using a stored
 * backend asset reference.
 *
 * Never accept a public ID directly from a client.
 */
export const deleteAccountAsset = async (asset) => {
  if (
    !asset ||
    typeof asset.publicId !== "string" ||
    !asset.publicId.trim() ||
    !ALLOWED_RESOURCE_TYPES.includes(asset.resourceType) ||
    asset.deliveryType !== "authenticated"
  ) {
    throw new AppError("Invalid account asset reference.", 400);
  }

  const cloudinary = getCloudinaryClient();

  try {
    const result = await cloudinary.uploader.destroy(asset.publicId, {
      resource_type: asset.resourceType,
      type: "authenticated",
      invalidate: true,
    });

    if (result.result !== "ok" && result.result !== "not found") {
      throw new Error("Cloudinary did not confirm asset deletion.");
    }

    return {
      deleted: result.result === "ok",
      alreadyMissing: result.result === "not found",
    };
  } catch {
    throw new AppError("Account file deletion failed. Please try again.", 502);
  }
};

// ============================================
// 3. GENERATE TEMPORARY DOWNLOAD URL
// ============================================

/**
 * Generates a time-limited URL for an authenticated asset.
 *
 * IMPORTANT:
 * Call this only after the relevant Customer or Staff
 * ownership and permission checks have succeeded.
 */
export const generateAccountAssetDownloadUrl = async (
  asset,
  {
    expiresInSeconds = DEFAULT_DOWNLOAD_EXPIRY_SECONDS,
    attachment = false,
  } = {},
) => {
  if (
    !asset ||
    typeof asset.publicId !== "string" ||
    !asset.publicId.trim() ||
    !ALLOWED_RESOURCE_TYPES.includes(asset.resourceType) ||
    asset.deliveryType !== "authenticated"
  ) {
    throw new AppError("Invalid account asset reference.", 400);
  }

  if (
    !Number.isInteger(expiresInSeconds) ||
    expiresInSeconds < 60 ||
    expiresInSeconds > 3600
  ) {
    throw new AppError(
      "Download link expiry must be between 60 and 3600 seconds.",
      400,
    );
  }

  if (
    typeof asset.format !== "string" ||
    !/^[a-zA-Z0-9]{1,10}$/.test(asset.format)
  ) {
    throw new AppError("The stored asset format is invalid.", 500);
  }

  const cloudinary = getCloudinaryClient();

  const expiresAt = Math.floor(Date.now() / 1000) + expiresInSeconds;

  try {
    return cloudinary.utils.private_download_url(asset.publicId, asset.format, {
      resource_type: asset.resourceType,
      type: "authenticated",
      expires_at: expiresAt,
      attachment,
    });
  } catch {
    throw new AppError("Could not generate a secure file download link.", 502);
  }
};

// ============================================
// BACKWARD-COMPATIBLE CUSTOMER EXPORTS
// ============================================

/**
 * Keeps existing Customer service imports working.
 */
export const uploadCustomerAsset = async ({
  buffer,
  mimeType,
  originalFilename,
  customerId,
  assetCategory,
}) => {
  return uploadAccountAsset({
    buffer,
    mimeType,
    originalFilename,
    accountType: "customers",
    accountId: customerId,
    assetCategory,
  });
};

export const deleteCustomerAsset = deleteAccountAsset;
